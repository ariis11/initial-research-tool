#!/usr/bin/env python3
"""extract_prep.py -- gather one paper's raw material for the agent to read.

Deterministic, no judgement: pull the PDF text and any highlights out of
Zotero into one working file, so the agent drafting the analysis is reading
the paper rather than guessing at it.

  python3 extract_prep.py --thread <thread> --bibkey mir2023delegatable
  python3 extract_prep.py --thread <thread> --all --limit 5
"""
from __future__ import annotations

import argparse, json, re, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import common as c

PREAMBLE = re.compile(r"^\*Response size:.*?\*\s*", re.S)


def zot(args, timeout=180) -> dict:
    p = subprocess.run(["zotero-cli", "--json", *args], capture_output=True,
                       text=True, timeout=timeout)
    try:
        return json.loads(p.stdout)
    except json.JSONDecodeError:
        return {"ok": False, "error": {"message": (p.stderr or p.stdout)[:300]}}


HEAD_PAGES = 22          # front matter, model, mechanism, usually evaluation
TAIL_PAGES = 10          # where the bibliography lives
WHOLE_IF_UNDER = 34      # short paper: take all of it rather than stitching


def _read(item_key: str, a: int, b: int) -> tuple[str, int]:
    """-> (text, total pages). Total is parsed from the reader's own header."""
    r = zot(["read", item_key, "--start-page", str(a), "--end-page", str(b)])
    if not r.get("ok"):
        return "", 0
    txt = (r.get("data") or {}).get("text") or ""
    # The reader prints "**Total pages in PDF:** 8" -- matching \s* after the
    # colon fails on the markdown bold, which silently made every paper take
    # the no-total branch: a 22-page head, no tail, no bibliography, and no GAP
    # marker to tell the reading agent what it had not seen. \D* instead.
    m = re.search(r"Total pages in PDF:\D*(\d+)", txt)
    return txt, int(m.group(1)) if m else 0


def fulltext(item_key: str) -> str:
    """The paper's text, including its bibliography.

    `get fulltext` silently returns only the first 10 pages. Two extraction
    agents caught it independently: references_count came back null almost
    everywhere, cites_pre_2015 could not be answered at all, and -- the real
    damage -- some `revocation: null` entries meant "the section was in the
    pages we never read" rather than "the paper is silent". That distinction
    is the whole basis of this review's central claim, so a cap that quietly
    breaks it is not survivable.

    Pages are requested explicitly instead. A short paper is taken whole; a
    long one is taken as a head and a tail, with the gap marked in the text so
    the agent reading it knows what it has not seen and can say so rather than
    guess.
    """
    probe, total = _read(item_key, 1, 1)
    if not probe:
        return ""
    if total and total <= WHOLE_IF_UNDER:
        txt, _ = _read(item_key, 1, total)
        return PREAMBLE.sub("", txt)
    if not total:
        txt, _ = _read(item_key, 1, HEAD_PAGES)
        return PREAMBLE.sub("", txt)
    head, _ = _read(item_key, 1, HEAD_PAGES)
    tail, _ = _read(item_key, max(HEAD_PAGES + 1, total - TAIL_PAGES + 1), total)
    gap = (f"\n\n> **GAP: pages {HEAD_PAGES + 1}-{total - TAIL_PAGES} of {total} "
           f"are not included.** Anything you cannot find here may be in those "
           f"pages. Record such a field as null with an `unanswered` entry saying "
           f"the section was not read -- do NOT record it as the paper being "
           f"silent.\n\n")
    return PREAMBLE.sub("", head) + gap + PREAMBLE.sub("", tail)


def annotations(item_key: str) -> list[dict]:
    r = zot(["annotations", "list", "--item-key", item_key, "--pdf-extraction"])
    if not r.get("ok"):
        r = zot(["annotations", "list", "--item-key", item_key])
    if not r.get("ok"):
        return []
    d = r.get("data") or {}
    return d.get("annotations") or d.get("items") or []


def prep_one(row: dict, outdir: Path) -> Path | None:
    key = row.get("zotero_key")
    if not key:
        c.log(f"  {row['bibkey']}: no zotero_key — run ingest.py first")
        return None
    text = fulltext(key)
    if not text:
        c.log(f"  {row['bibkey']}: no readable full text — Gate C, fetch the PDF")
        return None
    anns = annotations(key)
    outdir.mkdir(parents=True, exist_ok=True)
    path = outdir / f"{row['bibkey']}.md"
    parts = [
        f"# Working material — {row['bibkey']}", "",
        "*Generated by extract_prep.py. Input for drafting the analysis file;",
        "not itself an artefact. Every claim in the analysis must quote from the",
        "full text below, verbatim — extract_check.py string-matches them.*", "",
        "## Item", "",
        f"- **bibkey**: `{row['bibkey']}`", f"- **zotero_key**: `{key}`",
        f"- **title**: {row.get('title','')}", f"- **authors**: {row.get('authors','')}",
        f"- **year**: {row.get('year','')}", f"- **venue**: {row.get('venue','')}",
        f"- **doi**: {row.get('doi','')}", f"- **arxiv**: {row.get('arxiv','')}", "",
    ]
    if anns:
        parts += [f"## Highlights ({len(anns)})", ""]
        for an in anns:
            txt = " ".join((an.get("text") or an.get("annotationText") or "").split())
            com = " ".join((an.get("comment") or an.get("annotationComment") or "").split())
            colour = an.get("color") or an.get("annotationColor") or ""
            page = an.get("pageLabel") or an.get("annotationPageLabel") or ""
            if txt or com:
                parts.append(f"- [{colour} p.{page}] {txt}" + (f"  — *{com}*" if com else ""))
        parts.append("")
    else:
        parts += ["## Highlights", "", "*None. The analysis is drafted from the full text alone.*", ""]
    parts += [f"## Full text ({len(text):,} characters)", "", "```text", text, "```", ""]
    path.write_text("\n".join(parts), encoding="utf-8")
    c.log(f"  {row['bibkey']}: {len(text):,} chars, {len(anns)} highlights → {path.name}")
    return path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--thread", type=Path, required=True)
    ap.add_argument("--bibkey", action="append", default=[])
    ap.add_argument("--all", action="store_true", help="every ingested row not yet extracted")
    ap.add_argument("--papers", type=Path, help="papers/ dir (default: <thread>/../../papers)")
    ap.add_argument("--limit", type=int)
    a = ap.parse_args()

    rows = c.read_rows(a.thread / "candidates.csv")
    papers = c.papers_dir(a.thread, a.papers)
    if a.bibkey:
        todo = [r for r in rows if r["bibkey"] in set(a.bibkey)]
    elif a.all:
        todo = [r for r in rows if r.get("zotero_key")
                and not (papers / f"{r['bibkey']}.md").exists()]
    else:
        c.log("pass --bibkey or --all")
        return 2
    if a.limit:
        todo = todo[:a.limit]
    if not todo:
        c.log("nothing to prepare.")
        return 0
    out = a.thread / "extraction-workspace"
    c.log(f"preparing {len(todo)} paper(s) → {out}")
    made = [p for r in todo if (p := prep_one(r, out))]
    c.write_run(a.thread, "extract-prep", {"requested": len(todo), "prepared": len(made)})
    return 0


if __name__ == "__main__":
    sys.exit(main())
