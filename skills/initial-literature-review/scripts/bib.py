#!/usr/bin/env python3
"""bib.py -- write library.bib ourselves, with OUR citation keys.

NEVER export the bibliography from Zotero. Verified on 23 September: an item
whose citation key was pinned to `mir2023delegatable` still exported as
`@article{Mir2023_3QNXCRIJ}`. Zotero holds an item key, not a citation key,
and its exporters invent one at export time. Any bibliography taken from
Zotero therefore carries keys that do not match the analysis filenames, the
CSVs, or anything you have already cited.

So: metadata is read OUT of Zotero, which keeps hand corrections made in the
UI; the key is supplied by us, which keeps it stable. Both halves right.

  python3 bib.py --papers research/papers --out research/library.bib
  python3 bib.py --thread <thread> --out ...     # from candidates.csv instead
"""
from __future__ import annotations

import argparse, json, re, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import common as c

try:
    import yaml
except ImportError:
    yaml = None

ENTRY = {"journalArticle": "article", "conferencePaper": "inproceedings",
         "book": "book", "bookSection": "incollection", "thesis": "phdthesis",
         "report": "techreport", "preprint": "misc", "manuscript": "misc",
         "computerProgram": "misc", "webpage": "misc", "document": "misc"}
FM = re.compile(r"^---\n(.*?)\n---\n", re.S)
SPECIAL = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_"}


def esc(s: str) -> str:
    out = "".join(SPECIAL.get(ch, ch) for ch in str(s or ""))
    return " ".join(out.split())


def zot(args, timeout=60) -> dict:
    p = subprocess.run(["zotero-cli", "--json", *args], capture_output=True,
                       text=True, timeout=timeout)
    try:
        return json.loads(p.stdout)
    except json.JSONDecodeError:
        return {"ok": False}


def meta(item_key: str) -> dict | None:
    r = zot(["get", "metadata", item_key])
    if not r.get("ok"):
        return None
    return ((r.get("data") or {}).get("data")) or None


def entry(bibkey: str, d: dict) -> str:
    kind = ENTRY.get(d.get("itemType", ""), "misc")
    authors = " and ".join(
        (f"{cr.get('lastName','')}, {cr.get('firstName','')}".strip(", ")
         or cr.get("name", ""))
        for cr in (d.get("creators") or []) if cr.get("creatorType") == "author")
    year = ""
    if m := re.search(r"(19|20)\d{2}", str(d.get("date", ""))):
        year = m.group(0)
    fields = {
        "title": d.get("title"), "author": authors, "year": year,
        "booktitle" if kind == "inproceedings" else "journal":
            d.get("proceedingsTitle") or d.get("publicationTitle"),
        "volume": d.get("volume"), "number": d.get("issue"),
        "pages": d.get("pages"), "publisher": d.get("publisher"),
        "doi": d.get("DOI"), "url": d.get("url"), "issn": d.get("ISSN"),
        "note": d.get("extra") if not (d.get("extra") or "").startswith("Citation Key") else "",
    }
    lines = [f"@{kind}{{{bibkey},"]
    for k, v in fields.items():
        if v:
            lines.append(f"  {k:9s} = {{{esc(v)}}},")
    lines.append("}")
    return "\n".join(lines)


def pairs_from_papers(papers: Path):
    for f in sorted(p for p in papers.glob("*.md") if not p.name.startswith("_")):
        m = FM.match(f.read_text(encoding="utf-8"))
        if not m or yaml is None:
            continue
        try:
            fm = yaml.safe_load(m.group(1)) or {}
        except yaml.YAMLError:
            continue
        if fm.get("zotero_key"):
            yield fm.get("bibkey") or f.stem, fm["zotero_key"]


def pairs_from_thread(thread: Path):
    for r in c.read_rows(thread / "candidates.csv"):
        if r.get("zotero_key") and r.get("bibkey"):
            yield r["bibkey"], r["zotero_key"]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--papers", type=Path)
    ap.add_argument("--thread", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()

    if not (a.papers or a.thread):
        c.log("pass --papers or --thread")
        return 2
    pairs = list(pairs_from_papers(a.papers) if a.papers else pairs_from_thread(a.thread))
    seen, uniq = set(), []
    for k, z in pairs:
        if k not in seen:
            seen.add(k); uniq.append((k, z))
    if not uniq:
        c.log("no bibkey ↔ zotero_key pairs found — run ingest.py first")
        return 2

    entries, missing = [], []
    for bibkey, zkey in uniq:
        d = meta(zkey)
        if not d:
            missing.append(bibkey); continue
        entries.append(entry(bibkey, d))

    header = ["% library.bib — generated by bib.py. Do not edit by hand.",
              f"% {c.now_iso()} · {len(entries)} entries",
              "% Keys are OURS, generated at dedupe and stable. Never regenerate",
              "% this file by exporting from Zotero: its exporters invent their own",
              "% keys and the citations will silently stop matching.", ""]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(header) + "\n\n".join(entries) + "\n", encoding="utf-8")
    c.log(f"{len(entries)} entries → {a.out}")
    if missing:
        c.log(f"  {len(missing)} could not be read from Zotero: {', '.join(missing[:5])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
